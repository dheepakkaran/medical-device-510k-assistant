"""Build RESULTS.md from results/*.json (no hand-typed numbers)."""
import json
from pathlib import Path

etl = json.loads(Path("results/etl_log.json").read_text())
ret = json.loads(Path("results/retrieval.json").read_text())
ans = json.loads(Path("results/answers.json").read_text())["summary"]
L = ledger = [json.loads(l) for l in Path("results/cost_ledger.jsonl").read_text().splitlines()]
total = sum(r["cost_usd"] for r in L)
out = ["# Results", "", "All numbers below are generated by `scripts/make_results.py` from `results/*.json`.", "",
       "## ETL (openFDA 510(k), run " + etl["run_date"] + ")", "", "| Product code | Device type | Rows in | Dropped | Loaded |", "|---|---|---|---|---|"]
for c, v in etl["codes"].items():
    out.append(f"| {c} | {v['name']} | {v['rows_in']} | {v['rows_dropped']} | {v['rows_loaded']} |")
out += [f"", f"Total rows in `devices`: **{etl['total_loaded']}**", "",
        "## Retrieval: 20 frozen questions (gold = guidance doc + page)", "",
        "| Method | hit@1 | hit@3 | hit@5 |", "|---|---|---|---|"]
for m, v in ret["methods"].items():
    out.append(f"| {m} | {v['hit@1']}/20 | {v['hit@3']}/20 | {v['hit@5']}/20 |")
c, n, s, c10 = ans["cascade_test20"], ans["cascade_negatives"], ans["strong_only_q01_q10"], ans["cascade_q01_q10"]
out += ["", "## Cited answers (app default: hybrid retrieval, top 5)", "",
        "| Run | Questions | Answered | All quotes verified | Cites a gold page | Escalated to Opus | Cost |", "|---|---|---|---|---|---|---|",
        f"| Cascade (Haiku 5.5 → Opus 5.5 only on a failed quote check) | {c['n']} | {c['answered']} | {c['all_quotes_verified']} | {c['cites_gold_page']} | {c['escalated_to_strong']} | ${c['cost_usd']:.4f} |",
        f"| Cascade, out-of-scope questions | {n['n']} | {n['answered']} (should be 0) | {n['all_quotes_verified']} | n/a | {n['escalated_to_strong']} | ${n['cost_usd']:.4f} |",
        f"| Cascade on q01–q10 | {c10['n']} | {c10['answered']} | {c10['all_quotes_verified']} | {c10['cites_gold_page']} | {c10['escalated_to_strong']} | ${c10['cost_usd']:.4f} |",
        f"| Opus 5.5 only on q01–q10 (ablation) | {s['n']} | {s['answered']} | {s['all_quotes_verified']} | {s['cites_gold_page']} | n/a | ${s['cost_usd']:.4f} |",
        "", f"Gold page was in the 5 retrieved passages for {c['gold_page_retrieved']}/20 questions, so retrieval, not the model, caps page accuracy.",
        "", f"Total API spend for every call in `results/cost_ledger.jsonl`: **${total:.4f}** ({len(L)} calls; budget $0.30)."]
Path("RESULTS.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
